/**
 * Generates src/lib/lead/logo.ts: the Medad-X mark as a small PNG, base64-encoded, which the
 * lead emails embed inline (cid:) so it shows even where mail apps block remote images.
 *
 *   npx tsx scripts/email-logo.ts
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// 76px = 2x the 38px it is shown at; flattened onto the tile colour so dark-mode inversion is harmless.
const png = await sharp(resolve(root, 'public/icons/icon-192.png'))
  .resize(76, 76)
  .flatten({ background: '#fcfaf3' })
  .png({ compressionLevel: 9, palette: true, quality: 90 })
  .toBuffer();

writeFileSync(
  resolve(root, 'src/lib/lead/logo.ts'),
  `/** Generated by scripts/email-logo.ts from public/icons/icon-192.png (76×76 PNG, ${png.length} bytes). Do not edit. */\n` +
    `export const LOGO_PNG_BASE64 =\n  '${png.toString('base64')}';\n`,
);
console.log(`logo.ts written (${png.length} bytes)`);
